"""The requirements lockfile check itself.

The failure it exists for is dull and common: someone edits ``requirements/*.in`` and forgets
to recompile, so the intent and the locked set disagree and the next CI run installs
something nobody asked for. It is a text comparison rather than a CI ``pip-compile
--dry-run`` because re-resolving torch, mlflow and akshare with hashes takes about twenty
minutes per file and needs the network.

A check that cannot fail is worse than none, so the cases below include what it must reject.
"""

import importlib.util
from pathlib import Path

from django.test import SimpleTestCase

REPO_ROOT = Path(__file__).resolve().parents[2]

LOCK_OK = """\
#
# This file is autogenerated by pip-compile with Python 3.12
#
celery==5.4.0 \\
    --hash=sha256:bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb
django==6.0.1 \\
    --hash=sha256:aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa
kombu==5.6.2 \\
    --hash=sha256:cccccccccccccccccccccccccccccccccccccccccccccccccccccccccccccccc
"""

INTENT_OK = """\
django==6.0.1
celery==5.4.0
kombu==5.6.2
"""


def _load():
    path = REPO_ROOT / 'scripts' / 'check_requirements_lockfile.py'
    spec = importlib.util.spec_from_file_location('check_requirements_lockfile', path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


checker = _load()


class LockfileCheckTests(SimpleTestCase):
    def _problems(self, files):
        import tempfile

        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            for name, content in files.items():
                (root / name).write_text(content, encoding='utf-8')
            return checker.collect_problems(pairs=('base',), root=root)

    def test_a_consistent_pair_has_no_problems(self):
        self.assertEqual(self._problems({'base.in': INTENT_OK, 'base.txt': LOCK_OK}), [])

    def test_a_forgotten_recompile_is_rejected(self):
        intent = INTENT_OK.replace('celery==5.4.0', 'celery==5.5.0')
        problems = self._problems({'base.in': intent, 'base.txt': LOCK_OK})
        self.assertTrue(any('celery locks 5.4.0 but the .in asks 5.5.0' in p for p in problems))

    def test_a_direct_pin_missing_from_the_lockfile_is_rejected(self):
        problems = self._problems({'base.in': INTENT_OK + 'newdep==1.0.0\n',
                                   'base.txt': LOCK_OK})
        self.assertTrue(any('newdep==1.0.0 is not locked' in p for p in problems))

    def test_an_unhashed_lockfile_line_is_rejected(self):
        unhashed = LOCK_OK.replace(
            'kombu==5.6.2 \\\n'
            '    --hash=sha256:cccccccccccccccccccccccccccccccccccccccccccccccccccccccccccccccc\n',
            'kombu==5.6.2\n',
        )
        problems = self._problems({'base.in': INTENT_OK, 'base.txt': unhashed})
        self.assertTrue(any('kombu has no --hash line' in p for p in problems))

    def test_a_lockfile_that_still_includes_another_file_is_rejected(self):
        problems = self._problems({'base.in': INTENT_OK,
                                   'base.txt': '-r base.txt\n' + LOCK_OK})
        self.assertTrue(any('must be flattened' in p for p in problems))

    def test_a_missing_file_is_rejected_rather_than_ignored(self):
        problems = self._problems({'base.in': INTENT_OK})
        self.assertTrue(any('base.txt: file is missing' in p for p in problems))

    def test_pin_names_are_compared_case_and_separator_insensitively(self):
        """PyPI treats Django, django and DJANGO as one project, and the compiled file may
        spell a normalised name differently from the .in."""
        lock = LOCK_OK + (
            'django-something==1.0.0 \\\n'
            '    --hash=sha256:dddddddddddddddddddddddddddddddddddddddddddddddddddddddddddddddd\n'
        )
        self.assertEqual(
            self._problems({'base.in': 'Django_Something==1.0.0\n', 'base.txt': lock}), [])


class RealRepositoryTests(SimpleTestCase):
    def test_the_checked_in_lockfiles_are_consistent(self):
        """The actual tree, not a fixture. This is what CI runs."""
        problems = checker.collect_problems()
        self.assertEqual(problems, [], '\n'.join(problems))

    def test_every_direct_pin_carries_a_hash(self):
        """Hash mode is the point of the lockfile; this asserts it reached every line."""
        for stem in checker.PAIRS:
            locked, _includes = checker.locked_pins(REPO_ROOT / 'requirements' / f'{stem}.txt')
            unhashed = [name for name, (_, hashes) in locked.items() if not hashes]
            self.assertEqual(unhashed, [], f'{stem}.txt has unhashed packages')