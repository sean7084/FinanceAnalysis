"""ETF rotation API serialisation.

The signal, position, universe, daily and feature viewsets are read-only, so their
serializers decide **what a list response costs** and nothing more:

``ETFDaily`` and ``ETFFeatureSnapshot`` are multi-million-row tables joined to
``ETFUniverse``, so the fund identity is flattened onto every row (``etf_ts_code``,
``etf_name``) rather than making a client fetch the universe for each bar.

A signal's ``rankings`` is one entry per rankable fund -- ~500 objects per row -- and a
backtest's ``equity_curve``/``trade_log``/``report`` grow with the window and the number
of legs. All four are detail-only: list payloads carry the summary columns and the
selection, never the blobs.

``ETFRotationBacktestSerializer`` is the exception -- the workbench POSTs runs -- and it
carries the same two responsibilities ``apps/backtest/serializers.py`` does:

**Which knobs a caller may set.** Only the dimensions of a run are writable. ``parameters``
and the fingerprint inside it are generated by ``BacktestConfig.to_parameters()``, and
``report['runtime_state']`` is the engine's resumable cursor, so accepting either from a
client would break both dedupe and restart-resume; the fee knobs and ``walk_forward_steps``
are read-only because a run launched from the UI should cost what every other run costs.

**Rejecting a config the engine cannot honour.** Rule-only, date ordering and the positive
counters fail here with a 400 rather than as a ``BacktestConfigError`` in a worker, which
would leave the row ``FAILED`` and the reason in ``error_message`` instead of the response.

The feature column list is spelled out rather than imported from ``features.FEATURE_COLUMNS``,
because that module imports TA-Lib and pandas at module scope and serializers are
reachable from ``config/urls.py``. Adding a feature therefore needs a deliberate edit
here; a silently-growing API response is the worse failure.
"""

