#!/usr/bin/env python
"""Stop a recompile that silently moves a critical pin.

``check_requirements_lockfile.py`` proves the ``.txt`` matches the ``.in`` intent; it cannot
see that a *transitive* pin moved, because the ``.in`` never named it. Re-resolution is exactly
when that happens: ``torch`` carries the CUDA closure (``nvidia-*``, ``triton``), and moving
``lightgbm`` changes whether a GPU device exists at all. A green CI is not evidence that the
closure stayed put -- the tests exercise the installed packages, not the diff.

So this compares the committed lockfiles against the freshly compiled ones and fails on any
movement, addition or removal of a watched name. ``daphne`` is watched precisely because #149
deleted it: a recompile that reintroduces it has undone the decision.

Usage::

    python scripts/check_pin_drift.py                  # worktree vs origin/main
    python scripts/check_pin_drift.py --self-test      # prove the gate can fail
    python scripts/check_pin_drift.py --ref HEAD~1 --require-header 3.14
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]

#: Names whose movement changes the GPU runtime, the provider surface or the deployment story.
WATCHED_EXACT = ('torch', 'mlflow', 'akshare', 'lightgbm', 'channels', 'daphne')
WATCHED_PREFIX = ('nvidia-',)
PIN_RE = re.compile(r'^([A-Za-z0-9._-]+)\s*==\s*([^\s]+)$')


def watched(name: str) -> bool:
    return name in WATCHED_EXACT or name.startswith(WATCHED_PREFIX)


def parse(text: str) -> dict:
    """``{normalised name: version}`` for the pinned lines of a compiled lockfile."""
    pins = {}
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith('#'):
            continue
        stripped = stripped.split('\\', 1)[0].strip()
        stripped = stripped.split(';', 1)[0].strip()
        match = PIN_RE.match(stripped)
        if match:
            pins[match.group(1).lower()] = match.group(2)
    return pins


def compare(old: dict, new: dict) -> list:
    findings = []
    for name in sorted(set(old) | set(new)):
        if not watched(name):
            continue
        before, after = old.get(name), new.get(name)
        if before == after:
            continue
        if before is None:
            findings.append(f'ADDED   {name}=={after}')
        elif after is None:
            findings.append(f'REMOVED {name}=={before}')
        else:
            findings.append(f'MOVED   {name}: {before} -> {after}')
    return findings


def header_declares(text: str, version: str) -> bool:
    """The generated header must name the target interpreter.

    pip-compile writes "with Python 3.14"; uv writes the command line it ran, which carries
    "--python-version 3.14". Both are machine-checkable declarations; neither may be absent.
    """
    head = text.split('\n\n', 1)[0]
    return (
        f'Python {version}' in head
        or f'--python-version {version}' in head
        or f'--python-version={version}' in head
    )


def git_show(ref: str, path: str) -> str:
    return subprocess.run(
        ['git', 'show', f'{ref}:{path}'], capture_output=True, text=True, check=True,
    ).stdout


def self_test() -> int:
    """Every assertion here has a negative control: a gate that cannot fail is not a gate."""
    base = 'torch==2.12.0 \\\n    --hash=sha256:aa\nnvidia-cublas-cu13==13.0.0.1 \\\nmlflow==3.9.0\n'
    old = parse(base)
    rc = 0

    def check(label, condition):
        nonlocal rc
        if condition:
            print(f'self-test ok: {label}')
        else:
            print(f'SELF-TEST FAIL: {label}')
            rc = 1

    check('identical text -> no drift', not compare(old, parse(base)))
    moved = base.replace('torch==2.12.0', 'torch==2.13.0')
    check('injected torch move caught',
          any(f.startswith('MOVED   torch') for f in compare(old, parse(moved))))
    removed = base.replace('nvidia-cublas-cu13==13.0.0.1 \\\n', '')
    check('injected nvidia removal caught',
          any(f.startswith('REMOVED nvidia-cublas-cu13') for f in compare(old, parse(removed))))
    added = base + 'daphne==4.1.2\n'
    check('daphne re-addition caught',
          any(f.startswith('ADDED   daphne') for f in compare(old, parse(added))))
    check('marker-suffixed pin parsed',
          parse('torch==2.12.0; python_version >= "3.14"').get('torch') == '2.12.0')
    check('unwatched pin ignored', not compare(old, parse(base + 'zipp==4.1.2\n')))

    uv_head = ('# This file was autogenerated by uv via the following command:\n'
               '#    uv pip compile --generate-hashes --python-version 3.14 -o requirements/base.txt\n')
    pip_head = '# This file is autogenerated by pip-compile with Python 3.14\n'
    for label, text, want in (
        ('uv header accepted', uv_head, True),
        ('pip-compile header accepted', pip_head, True),
        ('wrong-version header rejected', '# compiled with Python 3.12\n', False),
        ('versionless header rejected', '# autogenerated\n', False),
    ):
        check(label, header_declares(text, '3.14') is want)

    print(f'self_test_rc={rc}')
    return rc


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--worktree', default=str(PROJECT_ROOT))
    parser.add_argument('--ref', default='origin/main', help='Ref holding the committed lockfiles.')
    parser.add_argument('--require-header', default='3.14',
                        help='Interpreter the generated header must declare; empty to skip.')
    parser.add_argument('--self-test', action='store_true')
    args = parser.parse_args()

    if args.self_test:
        return self_test()

    root = Path(args.worktree)
    rc = 0
    for stem in ('base', 'local'):
        rel = f'requirements/{stem}.txt'
        new_path = root / rel
        if not new_path.is_file():
            print(f'MISSING {new_path}')
            rc = 1
            continue
        new_text = new_path.read_text(encoding='utf-8')
        old_text = git_show(args.ref, rel)
        if args.require_header and not header_declares(new_text, args.require_header):
            print(f'HEADER {stem}.txt does not declare Python {args.require_header}')
            rc = 1
        findings = compare(parse(old_text), parse(new_text))
        print(f'--- {stem}.txt: {len(findings)} watched-pin change(s) ---')
        for finding in findings:
            print('  ' + finding)
        if findings:
            rc = 1
        else:
            print('  no watched pin moved')
    print(f'pin_gate_rc={rc}')
    return rc


if __name__ == '__main__':
    sys.exit(main())